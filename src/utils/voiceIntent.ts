/**
 * تصنيف الأوامر الصوتية القصيرة — **نصٌّ خالص، بلا شبكة ولا نموذج**.
 *
 * «اعتمد» و«التالي» كلمةٌ واحدة: رفعُها ملفاً صوتياً إلى نموذجٍ سحابيّ وانتظارُ ثانيتين
 * ثمنٌ لا يقابله شيء. فالتعرّفُ يقع في المتصفح ({@link ./speechCommands}) والتصنيفُ هنا،
 * فيقع التنفيذ في اللحظة التي تُنطق فيها الكلمة.
 *
 * ⚠️ **مرآةٌ لـ`App\Services\Ai\VoiceCommandService`** في الخادم — القواعد والترتيب
 * والتطبيع واحدٌ في الملفّين. الخادمُ يبقى مساراً احتياطياً للمتصفحات التي لا تدعم
 * التعرّف على الكلام، فأيُّ تعديلٍ هنا يُنقل هناك (واختباراته هي المرجع: 25 عبارة).
 */

export type VoiceIntent = 'approve' | 'next' | 'previous' | 'edit' | 'cancel' | 'unknown';

/**
 * 🩸 الجذور مكتوبةٌ **بعد التطبيع** لا بصيغتها الإملائية: التطبيع يحذف الهمزة ويوحّد
 * الألف، فـ«إنشاء» تصير «انشا» و«أنشئ» تصير «انشي» — ووضعُ «انشاء» هنا لا يطابق شيئاً.
 */
const APPROVE_CORE =
  'اعتمد|عتمد|اعتماد|وافق|موافق|موافقه|تمام|تم|اوكي|اوك|okay|ok|نعم|ايه|ايوه|ايو|صح|زين|ممتاز|انش|احفظ|حفظ|سجل|خلاص|يلا|اكيد|اجل';

const NEGATION = 'لا|ما|مو|مب|مهوب|مش';

/**
 * القواعد **مرتّبة**: أوّل نمطٍ يطابق يفوز. والترتيبُ نفسُه هو المنطق — النفيُ قبل
 * الإثبات، والإلغاءُ قبل التعديل، والتعديلُ قبل التنقّل، والاعتمادُ أخيراً؛ كي لا يبتلع
 * «اعتمد» عبارةَ «لا تعتمد» ولا «عدّل ثم اعتمد».
 */
const RULES: Array<[RegExp, VoiceIntent]> = [
  // ١) النفي الملتصق بأيّ لفظ إثبات: «لا تعتمد»، «ما وافق»، «ما تم شي»
  [new RegExp(`(?:^|\\s)(?:${NEGATION})\\s*(?:ال)?[تي]?(?:${APPROVE_CORE})`, 'u'), 'cancel'],
  // ٢) نفي الرغبة: «ما ابي»، «مو ودي»
  [new RegExp(`(?:^|\\s)(?:${NEGATION})\\s*(?:ابي|ابغي|ابغا|اب|ودي|اريد)`, 'u'), 'cancel'],
  // ٣) الإلغاء الصريح — «الغ» جذرٌ يغطّي ألغِ/إلغاء/الغيها بعد التطبيع
  [/(?:^|\s)(?:ال)?(?:الغ|لغي|تراجع|بطل|اوقف|احذف|انسه|انسها|اتركه|اتركها|cancel)/u, 'cancel'],
  // ٤) «لا» وحدها جواباً
  [/^\s*(?:لا|كلا|لا لا|no)\s*$/u, 'cancel'],
  // ٥) التعديل
  [/(?:^|\s)(?:ال)?(?:عدل|تعديل|عدلي|غير|تغيير|صحح|تصحيح|اصلح|بدل|edit)/u, 'edit'],
  // ٦) الرجوع
  [/(?:^|\s)(?:ال)?(?:سابق|سابقه|ارجع|رجوع|رجعني|قبله|قبلها|وراء|back|previous)/u, 'previous'],
  // ٧) التالي
  [/(?:^|\s)(?:ال)?(?:تالي|تاليه|بعده|بعدها|كمل|واصل|استمر|next)/u, 'next'],
  // ٨) الاعتماد
  [new RegExp(`(?:^|\\s)(?:ال)?(?:${APPROVE_CORE})`, 'u'), 'approve'],
];

/**
 * تطبيع عربيّ خفيف: يُحذف التشكيل والتطويل، وتُوحَّد أشكال الألف والهاء والياء،
 * ويصير الترقيم مسافات — كي تتساوى «إلغاء» و«الغاء» و«ألغاء» قبل المطابقة.
 */
export function normalizeArabicCommand(text: string): string {
  let out = text.toLowerCase().trim();

  // التشكيل (U+064B–U+0652) والألف الخنجرية والتطويل
  out = out.replace(/[ً-ْٰـ]/gu, '');

  const map: Record<string, string> = {
    أ: 'ا', إ: 'ا', آ: 'ا', ٱ: 'ا',
    ة: 'ه', ى: 'ي', ئ: 'ي', ؤ: 'و', ء: '',
  };
  out = out.replace(/[أإآٱةىئؤء]/gu, (c) => map[c] ?? c);

  // الترقيم فاصلٌ لا حرف — «اعتمد،» يجب أن تُقرأ «اعتمد»
  out = out.replace(/[^\p{L}\p{N}]+/gu, ' ');

  return out.replace(/\s+/gu, ' ').trim();
}

/** يعيد النيّة المفهومة من نصٍّ منطوق — `unknown` حين لا يطابق شيئاً */
export function classifyVoiceCommand(text: string): VoiceIntent {
  const normalized = normalizeArabicCommand(text);
  if (normalized === '') return 'unknown';

  for (const [pattern, intent] of RULES) {
    if (pattern.test(normalized)) return intent;
  }

  return 'unknown';
}
