/**
 * كتابةٌ آمنةٌ في `localStorage`.
 *
 * 🔴 سببُ وجوده عطلٌ حيّ (2026-08-17): مستخدمٌ في صفحة القضايا رأى
 * **«خطأ في جلب القضايا»** بينما القضايا وصلت وعُرضت. والعلّةُ أنّ
 * `localStorage.setItem` كان عارياً داخل `try` كبيرٍ يلفّ الجلبَ والعرض،
 * فرمى `QuotaExceededError` فالتقطه `catch` الخارجيُّ وعرض رسالةَ فشلِ جلب.
 * **فوجَّه المستخدمُ شكواه إلى الخادم، والعلّةُ في حصّة متصفّحه.**
 *
 * وسعةُ `localStorage` **5–10 ميجا للنطاق كلِّه مجتمعاً** — تتقاسمها صفحاتُ
 * القضايا والمهامّ والمستندات ولوحةُ التحكم. فامتلاءُ إحداها يُفشل كتابةَ
 * البقيّة، ولو كانت القيمةُ رقماً واحداً.
 *
 * · القيمةُ المرتجَعة `false` عند الفشل — لمن أراد أن يُعلم المستخدم. وتجاهلُها
 *   مقصودٌ في أغلب المواضع: الكاشُ رفاهيةٌ لا تُفشل عملاً نجح.
 * · وعند الفشل **يُحذف المفتاح**: بلا ذلك تبقى نسخةٌ قديمةٌ تُقرأ عند كلّ فتحٍ
 *   ولا تُحدَّث أبداً (لأنّ الكتابة تفشل دائماً)، فيرى المستخدمُ بياناتٍ
 *   متقادمةً بلا أن يدري. **وغيابُ الكاش أصدقُ من قِدَمه.**
 */
export function safeSetItem(key: string, value: string): boolean {
    try {
        localStorage.setItem(key, value);
        return true;
    } catch {
        // الحذفُ نفسُه قد يرمي في أوضاعٍ نادرة (الخصوصيةُ الصارمة في سفاري)،
        // فلا يُترك عارياً هو الآخر.
        try {
            localStorage.removeItem(key);
        } catch {
            /* لا شيء يُفعَل — التخزينُ غيرُ متاحٍ أصلاً */
        }
        return false;
    }
}

/** قراءةٌ آمنة — `null` عند الغياب أو عند تعذّر الوصول إلى التخزين. */
export function safeGetItem(key: string): string | null {
    try {
        return localStorage.getItem(key);
    } catch {
        return null;
    }
}

/** حذفٌ آمن — لا يرمي مهما كانت حالة التخزين. */
export function safeRemoveItem(key: string): void {
    try {
        localStorage.removeItem(key);
    } catch {
        /* لا شيء يُفعَل */
    }
}
