import React from 'react';

interface Props {
  text: string;
  /** زرٌّ واحدٌ أو لا شيء — ولا يُرسَم زرٌّ لا يملك صاحبُ الشاشة صلاحيتَه. */
  action?: React.ReactNode;
}

/**
 * **قاعدةُ «البلوكُ الفارغُ سطرٌ»** — وهي التي تجعل الجدارَ يعمل في مكتبٍ فتح الوحدةَ
 * اليوم: سبعُ حالاتٍ فارغةٍ كاملةٍ (أيقونةٌ + عنوانٌ + وصفٌ + زرّ) = ثلاثُ شاشاتِ عدم،
 * بينما سبعةُ سطورٍ بـ44px = 308px تُقرأ في نظرة.
 *
 * · الارتفاعُ يُورَث من `.hrl-row` (44px)، والصنفُ `--static` يُلغي تلوينَ التحويم
 *   فلا يَعِد السطرُ بنقرةٍ لا تقع.
 * · **الحالةُ الكاملةُ (`hrl-state--empty`) تُحجَز للسطح الذي يملأ العمودَ كلَّه**:
 *   القائمةُ اليمنى · لوحُ المكتب · بوّابةُ الموظف · وبلوكُ الرصيد غير المُهيَّأ (لأنّه
 *   يشرح المرساةَ، وهي مفتاحُ وحدة الإجازات كلِّها).
 * · يُستعمل أيضاً لسطر «اعرض الكلّ (N)» في الاقتطاع.
 *
 * مستهلكوه يصلون في الخطوة ٤ (`ContractsTab` · `DocumentsTab` · `OnboardingTab` ·
 * `LeaveTabPanel`)؛ يُشحن هنا مع الجدار لأنّه جزءٌ من قاموسه لا من تلك الملفّات.
 */
export const EmptyLine: React.FC<Props> = ({ text, action }) => (
  <p className="hrl-row hrl-row--static">
    <span>{text}</span>
    {action}
  </p>
);

export default EmptyLine;
