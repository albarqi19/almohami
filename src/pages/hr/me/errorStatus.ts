/**
 * **رمزُ حالةِ HTTP من كائن الخطأ** — يقرؤه كلُّ أقسام `/my-hr` الأربعة.
 *
 * `apiClient` يُلحق `status` بكائن الخطأ منذ م٨ في فرعَي 403 والعامّ معاً. وبدون هذا
 * التمييز تنهار ثلاثُ حالاتٍ من ستٍّ إلى شاشةِ خطأٍ حمراءَ واحدة: ٤٠٤ «لا ملفَّ لحسابك»
 * (حالةٌ طبيعيةٌ في مكتبٍ فتح الوحدةَ للتوّ) و٤٠٣ «الميزةُ مطفأة» و٥٠٠ عطلٌ حقيقيّ —
 * فيُرسَل صاحبُ الحالة الطبيعية إلى الدعم، ويُطمأنُّ صاحبُ العطل الحقيقيّ.
 *
 * ══════ ولماذا وحدَها في ملفّ ══════
 * كانت مصدَّرةً من `MyHrPage.tsx` وتقرؤها منه أربعُ بطاقات، وذلك:
 * · **يكسر `react-refresh`** (`only-export-components`): ملفُّ مكوّنٍ يصدّر دالّةً عاديّة
 *   يفقد التحديثَ الساخن، فيُعاد تركيبُ الصفحة كلَّ تعديل.
 * · **ويصنع دائرةَ استيراد**: الصفحةُ تستورد البطاقات، والبطاقاتُ تستورد الصفحة.
 * وحدةٌ واحدةٌ بلا مكوّنات تقطع الأمرين معاً، والدالّةُ نفسُها لم يتغيّر منها حرف.
 */
export function errorStatus(error: unknown): number | undefined {
  if (typeof error !== 'object' || error === null) return undefined;
  const status = (error as { status?: unknown }).status;
  return typeof status === 'number' ? status : undefined;
}
