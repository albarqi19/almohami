import React from 'react';

/**
 * مرجعٌ نظاميّ («م.١١٧») — **رمزٌ مركّبٌ لا جملة**، فيُرسم بترتيبه المكتوب.
 *
 * العطل: النصُّ يُخزَّن «م.١١٧»، والخوارزميةُ ثنائيةُ الاتجاه ترفع مقطعَ الأرقام مستوىً فوق
 * الحرف العربيّ قبله، فيخرج على الشاشة **«١١٧.م»** — بادئةٌ صارت لاحقة. و`dir="ltr"` وحدَه
 * **لا يُصلحه** (قِيس: `span dir=ltr` و`bdi dir=ltr` كلاهما يعطي «١١٧.م»)، لأن الاتجاه الأساسيّ
 * لا يمنع مقطعَ الأرقام من أخذ مستواه. ولا `unicode-bidi: bidi-override` حلٌّ: يُصلح هذا الرمز
 * ويقلب حروفَ أيّ كلمةٍ عربيةٍ في مرجعٍ آخر («المادة» ⇒ «ةداملا»).
 *
 * العلاج: **عزلُ مقطع الأرقام وحدَه** (`<bdi>`) داخل تدفّقٍ من اليسار — فيبقى الحرفُ العربيّ
 * حيث كُتب، وتُقرأ الأرقامُ بترتيبها، وتبقى الكلمةُ العربيةُ — إن وردت يوماً في مرجع — سليمةَ
 * الحروف. و`<bdi>` أداةُ العزل القائمة في هذا المستودع (`AddExternalLinkModal`، `TaskDetail`).
 *
 * **لا يحمل صنفاً ولا يفرض محاذاة**: يُرسم `inline` داخل غلاف المُستدعي، فمحاذاةُ السطر تبقى
 * لصاحبها (البادئةُ المنطقية `start`) ولا يقفز الرمزُ إلى حافةٍ غير حافة اسمِه.
 */

/** مقاطعُ الأرقام: عربيةٌ (٠-٩) ولاتينيةٌ (0-9) وفارسية — بلا عَلَم `g` فلا حالةَ في `test`. */
const DIGIT_RUN = /([0-9٠-٩۰-۹]+)/;

interface Props {
  /** المرجعُ كما ورد من الخادم — الفارغُ لا يُرسم شيئاً (لا شرطةَ ولا فراغَ محجوز). */
  value?: string | null;
}

export const ArticleRef: React.FC<Props> = ({ value }) => {
  const text = (value ?? '').trim();

  if (text === '') return null;

  return (
    <span dir="ltr">
      {text
        .split(DIGIT_RUN)
        .filter((part) => part !== '')
        .map((part, index) =>
          DIGIT_RUN.test(part) ? (
            <bdi key={index}>{part}</bdi>
          ) : (
            <React.Fragment key={index}>{part}</React.Fragment>
          )
        )}
    </span>
  );
};

export default ArticleRef;
